#!/usr/bin/env python3
"""Generate supabase/migrations/20261111000004_seed_sources.sql from the Python source registry (single source of truth).

The seed inserts sources that do not exist yet and refreshes their permission metadata; it never touches operator choices
(enabled, schedule, budget, config) for rows that already exist. Run: python3 supabase/scripts/gen_source_seed.py [--check]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REG = ROOT / "poc" / "signal_engine" / "discovery" / "data" / "source_registry.json"
OUT = ROOT / "supabase" / "migrations" / "20261111000004_seed_sources.sql"
# connectors that exist in the engine and can run in the scheduled GitHub Actions collector
SCHEDULABLE = {"contracts_finder", "find_a_tender", "ted", "github_issues", "github_discussions", "rss_atom"}


def q(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    return "'" + str(v).replace("'", "''") + "'"


def arr(xs) -> str:
    return "array[" + ", ".join(q(x) for x in xs) + "]::text[]" if xs else "'{}'::text[]"


def build() -> str:
    reg = json.loads(REG.read_text())
    rows = []
    for s in reg["sources"]:
        automated = s["collection"] in ("api", "feed", "search")
        paid = str(s.get("cost", "free")).strip().lower() not in ("free", "")
        mr = s.get("marketplace_rules") or {}
        export_ok = bool(mr.get("export_or_retain") is True) or (s["status"] == "permitted" and s["family"] in ("procurement",))
        enabled = bool(s.get("enabled_by_default")) and s["status"] == "permitted" and not paid
        sched = "17 6 * * *" if (enabled and s["key"] in SCHEDULABLE) else None
        rows.append("(" + ", ".join([
            q(s["key"]), q(s["name"]), q(s["family"]), q(s["status"]), q(s["collection"]), q(s.get("connector")),
            q(enabled), q(automated), q(paid), q(export_ok), arr(s.get("pipelines") or []), q(s.get("contact_route")),
            q(s.get("notes")), q(s.get("evidence") if isinstance(s.get("evidence"), str) else json.dumps(s.get("evidence"))),
            q(sched), q(s.get("rate_limit") if isinstance(s.get("rate_limit"), str) else json.dumps(s.get("rate_limit"))),
            q(s.get("review_date")),
        ]) + ")")
    head = ("-- GENERATED by supabase/scripts/gen_source_seed.py from poc/signal_engine/discovery/data/source_registry.json.\n"
            "-- Do not edit by hand. Non-destructive: inserts new sources; for existing rows refreshes permission metadata only.\n\n")
    sql = head + ("insert into public.sources (key, name, family, permission_status, collection_mode, connector, enabled, automated, paid,\n"
                  "  export_allowed, pipelines, contact_route, notes, requirements, schedule_cron, rate_limit, review_date)\nvalues\n  ")
    sql += ",\n  ".join(rows)
    sql += ("\non conflict (key) do update set name = excluded.name, family = excluded.family, permission_status = excluded.permission_status,\n"
            "  collection_mode = excluded.collection_mode, connector = excluded.connector, automated = excluded.automated, paid = excluded.paid,\n"
            "  pipelines = excluded.pipelines, contact_route = excluded.contact_route, notes = excluded.notes, requirements = excluded.requirements,\n"
            "  rate_limit = excluded.rate_limit, review_date = excluded.review_date,\n"
            "  -- a permission downgrade switches automation off; operator choices are otherwise kept\n"
            "  enabled = case when excluded.permission_status in ('unknown', 'prohibited') then false else public.sources.enabled end;\n\n"
            "insert into public.app_settings (key, value) values\n"
            "  ('retention_days', '365'::jsonb),\n"
            "  ('llm', '{\"enabled\": false, \"provider\": null, \"model\": null, \"monthly_budget_usd\": 0, \"per_record_max_usd\": 0.01}'::jsonb),\n"
            "  ('email_notifications', '{\"enabled\": false, \"provider\": null}'::jsonb),\n"
            "  ('brave', '{\"enabled\": false, \"monthly_budget_usd\": 0, \"max_requests_per_run\": 100, \"storage_rights_attested\": false}'::jsonb)\n"
            "on conflict (key) do nothing;\n")
    return sql


def main() -> int:
    sql = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == sql
        print("seed in sync" if ok else "seed OUT OF DATE: run supabase/scripts/gen_source_seed.py")
        return 0 if ok else 1
    OUT.write_text(sql)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
